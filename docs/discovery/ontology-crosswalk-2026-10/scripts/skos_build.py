"""Generate the EDM vocabulary namespace stub (SKOS, Turtle) from crosswalk.csv.

Usage:
  python -I scripts/skos_build.py crosswalk.csv frameworks.json vocab/edm-vocab-v1.ttl

Seven v0.9 vocabularies are emitted: arc, tether, relationship, memory_type, temporal_profile, need, coping.
Each canonical value becomes a skos:Concept under https://emotionaldatamodel.org/vocab/<field>/v1#<value>.
Each crosswalk cell becomes a skos:*Match triple (exact -> exactMatch, broader -> broadMatch,
narrower -> narrowMatch, related -> relatedMatch). MFOEM targets use the OBO PURL. Every other target
is minted as a placeholder concept under https://emotionaldatamodel.org/xref/v1/<framework>#<slug>,
labelled with the crosswalk's target text and sourced to the framework citation URL, because those
frameworks publish no concept URIs. The namespace does not resolve yet; this is a proposal.
"""
import csv, json, re, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from v09_layout import DEPRECATED_VALUES

csv_path, fw_path, out_path = sys.argv[1:4]
VOCAB = 'https://emotionaldatamodel.org/vocab/{field}/v1'
XREF = 'https://emotionaldatamodel.org/xref/v1/{fw}'
FIELDS = {  # v0.9 vocabulary -> v0.8.3 source fields
 'arc': ['constellation.arc_type', 'constellation.narrative_arc'],
 'tether': ['gravity.tether_type'],
 'relationship': ['constellation.relational_dynamics'],
 'memory_type': ['constellation.memory_type'],
 'temporal_profile': ['constellation.temporal_rhythm'],
 'need': ['impulse.motivational_orientation'],
 'coping': ['impulse.coping_style'],
}
REL = {'exact': 'skos:exactMatch', 'broader': 'skos:broadMatch', 'narrower': 'skos:narrowMatch', 'related': 'skos:relatedMatch'}
META = {'row_id','domain','field','value','row_type','vocabulary','grounding','n_exact','n_broader','n_narrower','n_related','n_none','targets_verified_V/K/-'}

fw_doc = json.load(open(fw_path, encoding='utf-8'))
FW = {f['id']: f for f in fw_doc['frameworks']}
rows = list(csv.DictReader(open(csv_path, encoding='utf-8')))
fw_cols = [k for k in rows[0].keys() if k not in META]

def slug(s): return re.sub(r'_+', '_', re.sub(r'[^a-z0-9]+', '_', s.lower())).strip('_')
def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"')
CELL = re.compile(r'^(exact|broader|narrower|related): (.*?) \[([VK?\-])\](?: \((.*)\))?$')

def targets(label):
    """Split a crosswalk target label into individual target labels (';' and ' / ' separate alternatives)."""
    label = re.sub(r'\(.*?\)', '', label).strip()
    parts = [p.strip() for p in re.split(r';| / ', label) if p.strip()]
    return parts or [label]

def target_uri(fw, label):
    m = re.search(r'MFOEM:(\d{6})', label)
    if m: return f'<http://purl.obolibrary.org/obo/MFOEM_{m.group(1)}>', None
    return f'<{XREF.format(fw=fw)}#{slug(label)}>', label

xref_nodes = {}  # uri -> (fw, label, flags)
L = ['@prefix skos: <http://www.w3.org/2004/02/skos/core#> .', '@prefix owl: <http://www.w3.org/2002/07/owl#> .',
     '@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .', '@prefix dcterms: <http://purl.org/dc/terms/> .',
     '@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .', '@prefix edm: <https://emotionaldatamodel.org/vocab/> .', '',
     '# EDM vocabulary namespace stub, v1 (PROPOSED - the namespace does not resolve yet).',
     '# Generated by scripts/skos_build.py from crosswalk.csv; discovery output, not normative.',
     '# Mapping provenance per triple is recorded on the target placeholder concept (verification: V fetched list / K knowledge list / - free-form).', '']
n_match = 0
for field, sources in FIELDS.items():
    scheme = f'<{VOCAB.format(field=field)}>'
    L.append(f'{scheme} a skos:ConceptScheme ;')
    L.append(f'    skos:prefLabel "EDM {field} vocabulary v1"@en ;')
    L.append(f'    dcterms:source "EDM v0.8.3 {", ".join(sources)}" ;')
    L.append('    owl:versionInfo "1" .')
    L.append('')
    seen = set()
    for src in sources:
        for r in rows:
            if r['row_type'] != 'value' or f"{r['domain']}.{r['field']}" != src: continue
            v = r['value']
            uri = f'<{VOCAB.format(field=field)}#{v}>'
            dep = next((d for d in DEPRECATED_VALUES if d[0].endswith('.' + field) and d[1] == v), None)
            first = v not in seen
            if not first:
                L.append(f'# {v} already emitted from {sources[0]}; additional mappings from {src}')
                L.append(f'{uri}')
            else:
                L.append(f'{uri} a skos:Concept ;')
                L.append(f'    skos:inScheme {scheme} ;')
                L.append(f'    skos:prefLabel "{esc(v)}"@en ;')
                L.append(f'    skos:notation "{esc(v)}" ;')
                L.append(f'    dcterms:source "EDM v0.8.3 {src}={v} (grounding: {r["grounding"]})" ;')
                if dep:
                    L.append('    owl:deprecated true ;')
                    L.append(f'    skos:note "deprecated in v0.9: {esc(dep[3])}; still accepted as text"@en ;')
                    if dep[2]: L.append(f'    dcterms:isReplacedBy <{VOCAB.format(field=field)}#{dep[2]}> ;')
            seen.add(v)
            triples = []
            for fw in fw_cols:
                cell = r[fw]
                if cell == 'none': continue
                for part in cell.split(' || '):
                    m = CELL.match(part.strip())
                    if not m: raise SystemExit(f'unparsed cell {r["row_id"]} {fw}: {part}')
                    rel, label, flag, note = m.groups()
                    for t in targets(label):
                        tu, tl = target_uri(fw, t)
                        if tl: xref_nodes.setdefault(tu, (fw, tl, set()))[2].add(flag)
                        triples.append(f'    {REL[rel]} {tu} ;')
                        n_match += 1
            if not triples and first:
                L.append('    skos:note "orphan: no framework mapping in the crosswalk; EDM-specific"@en ;')
            L.extend(sorted(set(triples)))
            if L[-1].endswith(' ;'): L[-1] = L[-1][:-2] + ' .'
            elif not L[-1].endswith(' .'): L.pop(); L.pop()  # duplicate with no extra mappings: drop the dangling subject
            L.append('')

L.append('# ---- placeholder target concepts (frameworks without published concept URIs) ----')
L.append('')
for uri, (fw, label, flags) in sorted(xref_nodes.items()):
    cit = FW.get(fw, {}).get('citation', {})
    L.append(f'{uri} a skos:Concept ;')
    L.append(f'    skos:prefLabel "{esc(label)}"@en ;')
    L.append(f'    skos:inScheme <{XREF.format(fw=fw)}> ;')
    L.append(f'    rdfs:comment "placeholder for a {esc(FW.get(fw, {}).get("name", fw))} construct; verification flags: {"/".join(sorted(flags))}"@en ;')
    if cit.get('url'): L.append(f'    dcterms:source <{cit["url"]}> ;')
    L[-1] = L[-1][:-2] + ' .'
    L.append('')
for fw in sorted({fw for fw, _, _ in xref_nodes.values()}):
    f = FW.get(fw, {}); cit = f.get('citation', {})
    L.append(f'<{XREF.format(fw=fw)}> a skos:ConceptScheme ; skos:prefLabel "{esc(f.get("name", fw))} (EDM cross-reference placeholders)"@en' + (f' ; dcterms:source <{cit["url"]}>' if cit.get('url') else '') + ' .')
open(out_path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(f'vocabularies={len(FIELDS)} concepts={sum(1 for l in L if l.startswith("<https://emotionaldatamodel.org/vocab/") and " a skos:Concept" in l)} match_triples={n_match} placeholder_targets={len(xref_nodes)}')
