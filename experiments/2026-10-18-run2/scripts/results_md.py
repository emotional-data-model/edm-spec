"""RESULTS.md for run 2 from scoring/field_table.json, scoring/task_a_locomo.json, spend*.json and the raw checkpoints:
per slot x arm outcome against the frozen section-7 prediction, two-voter sensitivity beside the frozen three-voter verdict,
cross-arm equivalence, control gate, reported arms, null rates, per-extractor disagreement with the voting majority,
task (a), spend, deviations; then the ruling drafts (ruling-drafts.md, hand-written) verbatim.

Usage: python -P experiments/2026-10-18-run2/scripts/results_md.py
"""
import json, os, glob
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__)); EXP = os.path.dirname(HERE)
SLOTS = ['subject', 'trigger', 'harm', 'drive', 'integration', 'retrieval_cues', 'summary']
OLD = {'subject': 'anchor', 'trigger': 'spark', 'harm': 'wound', 'drive': 'fuel', 'integration': 'bridge', 'retrieval_cues': 'echo', 'summary': 'narrative'}
EXTRACTORS = ['claude-sonnet-5-5', 'claude-haiku-5-5', 'gpt-6.1-sol', 'kimi-k2.6', 'gpt-5.4-mini']
VOTERS = ['claude-sonnet-5-5', 'gpt-6.1-sol', 'kimi-k2.6']; TWO = ['claude-sonnet-5-5', 'gpt-6.1-sol']; REPORTED = ['claude-haiku-5-5', 'gpt-5.4-mini']
SHORT = {'claude-sonnet-5-5': 'Sonnet 5.5', 'claude-haiku-5-5': 'Haiku 5.5', 'gpt-6.1-sol': 'gpt-6.1-sol', 'kimi-k2.6': 'Kimi K2.6', 'gpt-5.4-mini': 'gpt-5.4-mini'}
ARMS = ('A', 'B'); CORPUS = ('synthetic', 'conversational', 'pepys')
# frozen section-7 predictions (experiment-plan-run2.md, freeze commit): acceptable Arm B outcomes; null condition B < A where stated
PRED = {'subject': ({'pass'}, False, 'pass'), 'trigger': ({'pass', 'interpretive'}, False, 'pass or interpretive'),
        'harm': ({'pass'}, True, 'pass; null rate falls'), 'drive': ({'interpretive'}, False, 'interpretive'),
        'integration': ({'pass'}, True, 'pass; null rate falls'), 'retrieval_cues': ({'pass'}, False, 'B (capped list) passes where the run-1 list did not; A echo is the comparison'),
        'summary': (None, False, 'control: same in both arms')}
RUN1_POOLED = {'subject': 'cut', 'trigger': 'cut', 'harm': 'cut', 'drive': 'cut', 'integration': 'pass (null-driven)', 'retrieval_cues': 'cut', 'summary': 'pass'}


def f(x): return '—' if x is None else f'{x:.2f}'


def reading(a, b):
    """the frozen section-7 decision table."""
    if a == 'pass' and b == 'pass': return 'reliable under either text'
    if a == 'pass': return 'v0.9 definition at fault (A passes, B does not)'
    if b == 'pass': return 'v0.8.3 text at fault (B passes, A does not)'
    if a == 'interpretive' and b == 'interpretive': return 'model-dependent under both'
    if a in ('cut', 'borderline-cut') and b in ('cut', 'borderline-cut'): return 'does not replicate under either text — founder decision'
    return f'neither passes (A {a}, B {b})'


def spend(name):
    p = os.path.join(EXP, name)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else {'total_usd': 0.0, 'calls': 0, 'by_model': {}}


def main():
    ft = json.load(open(os.path.join(EXP, 'scoring', 'field_table.json'), encoding='utf-8')); T = ft['table']
    ta = json.load(open(os.path.join(EXP, 'scoring', 'task_a_locomo.json'), encoding='utf-8'))
    sx, sp, sj = spend('spend.json'), spend('spend_pilot.json'), spend('spend_judge.json')
    # raw checkpoint facts
    raw_stats = Counter(); per_model = {m: Counter() for m in EXTRACTORS}; effort = set()
    for p in glob.glob(os.path.join(EXP, 'raw', '*', '*', '*.jsonl')):
        m = os.path.basename(os.path.dirname(os.path.dirname(p)))
        for l in open(p, encoding='utf-8'):
            if not l.strip(): continue
            r = json.loads(l); per_model[m]['calls'] += 1
            if r.get('transport_error'): per_model[m]['transport'] += 1
            elif r.get('parse_error'): per_model[m]['parse'] += 1
            elif r.get('missing_keys'): per_model[m]['missing_keys'] += 1
            if r.get('stop_reason') == 'max_tokens': per_model[m]['max_tokens'] += 1
    jbad = Counter()
    for p in glob.glob(os.path.join(EXP, 'raw', 'judge', '*.jsonl')):
        for l in open(p, encoding='utf-8'):
            if l.strip():
                r = json.loads(l); jbad['records'] += 1
                if not r.get('groups'): jbad['malformed'] += 1
    P = T['pooled']
    L = ['# RESULTS — run 2, prompt test on the six core slots (2026-10-18)\n']
    L.append('Generated by `scripts/results_md.py` from `scoring/field_table.json` (`scripts/score.py`), `scoring/task_a_locomo.json` (`scripts/task_a_locomo.py`), `spend*.json` and the checkpoints under `raw/`. Pre-registration: `docs/discovery/ontology-crosswalk-2026-10/experiment-plan-run2.md`, frozen by commit `run 2 pre-registration frozen` (`b1354ee`) before any call. Thresholds, voting rule, decision table and predictions are the frozen ones; nothing below was chosen after seeing the data. Nothing pushed.\n')
    L.append('## 0. Summary\n')
    tot = sx['total_usd'] + sp['total_usd'] + sj['total_usd']
    L.append(f"150 texts (synthetic 50, conversational 50, Pepys 50; byte-identical to run 1, sha256-checked) × 2 prompt arms × 5 extractors × 5 repeats = 7,500 extraction calls, plus 30 pilot calls and {sj['calls']} judge calls. **Spend USD {tot:.2f}** of the 60 hard stop (extraction {sx['total_usd']:.2f}, pilot {sp['total_usd']:.2f}, judge {sj['total_usd']:.2f}).\n")
    L.append('| Extractor | role | calls | valid | parse fail | missing keys | transport fail | USD |\n|---|---|---|---|---|---|---|---|')
    for m in EXTRACTORS:
        c = per_model[m]; role = 'voting' if m in VOTERS else 'reported'
        L.append(f"| `{m}` | {role} | {c['calls']} | {c['calls'] - c['transport'] - c['parse']} | {c['parse']} | {c['missing_keys']} | {c['transport']} | {sx['by_model'].get(m, {}).get('usd', 0):.2f} |")
    L.append(f"\nJudge (`claude-opus-5-5`, effort low): {jbad['records']} records, {jbad['malformed']} malformed after three attempts; judged (text, slot) units: {ft['judged_units']}.\n")
    g = P['_control_gate']
    L.append(f"**Control gate.** `summary` cross-model agreement (three voters) Arm A {f(g['summary_cross3_A'])} vs Arm B {f(g['summary_cross3_B'])}, difference {f(g['abs_diff'])}: **{'prompt-wide drift — the A / B comparison below is advisory only' if g['prompt_wide_drift'] else 'no prompt-wide drift; the A / B comparison stands'}**.\n")
    # headline
    held = []
    for s in SLOTS[:6]:
        acc, nullc, _ = PRED[s]; b = P[s]['B']['outcome3']; ok = b in acc
        if ok and nullc: ok = (P[s]['B']['null_rate']['voters'] or 0) < (P[s]['A']['null_rate']['voters'] or 0)
        held.append((s, ok))
    L.append(f"**Predictions.** {sum(1 for s, ok in held if ok)} of 6 frozen predictions held pooled ({', '.join(s for s, ok in held if ok) or 'none'}); not held: {', '.join(s for s, ok in held if not ok) or 'none'}. Per slot: §1.\n")
    L.append('### 0.1 Deviations from the pre-registration\n')
    L.append('| # | Deviation | Why | Logged |\n|---|---|---|---|')
    L.append('| R2-D1 | Parser takes the LAST complete top-level JSON object when an output holds several | pilot: Sonnet 5.5 (Arm A, P1665-06-15) emitted an object, then "Corrected output:" and a second object; run-1 parsing (first `{` to last `}`) fails such outputs. The value scored is the model\'s own final answer; nothing re-sampled | before the main run; `run_extraction.py` `parse_json2` |')
    L.append('| R2-D2 | Pilot of 30 calls (3 texts × 5 extractors × 2 arms), as the frozen plan §9 says, where the founder instruction of the same day said 12 | the frozen number was kept; cost USD ' + f"{sp['total_usd']:.2f}" + ' | this file |')
    L.append('| R2-D3 | The Anthropic prompt cache did not engage for the extraction prompts (Arm A ≈ 550 tokens, Arm B ≈ 800 tokens, both below the 1,024-token minimum cacheable prefix) | not a sampling change; cost only (input billed at the uncached rate; still under the stop) | this file |')
    L.append('')
    L.append('## 1. Per slot × arm outcome against the frozen prediction (pooled, 150 texts)\n')
    L.append('Statistics: judge-equivalence pair rate; repeatability per extractor over its five repeats (null included), cross-model over the three voting extractors\' modal classes (`cross3`; `nn` = populated answers only), thresholds 0.80 / 0.60. Outcome rule (R9): **pass** = all three voters ≥ 0.80 and cross3 ≥ 0.60; **interpretive** = all three ≥ 0.80, cross3 < 0.60; **cut** = ≥ 2 voters < 0.80; **borderline-cut** = exactly one voter < 0.80. Flags: *borderline* within 0.05 of a threshold; *sparse* null ≥ 90 %. Run-1 pooled outcome (47-field prompt) for reference.\n')
    L.append('| Slot (B / A) | run 1 | Arm | rep Sonnet / GPT / Kimi | cross3 (nn) | null (voters) | outcome | flags |\n|---|---|---|---|---|---|---|---|')
    for s in SLOTS:
        for arm in ARMS:
            r = P[s][arm]; fl = ', '.join(x for x, y in (('borderline', r['borderline']), ('sparse', r['sparse'])) if y)
            L.append(f"| `{s}` / `{OLD[s]}` | {RUN1_POOLED[s] if arm == 'A' else ''} | {arm} | {' / '.join(f(r['stat_repeat'][m]) for m in VOTERS)} | {f(r['cross3']['rate'])} ({f(r['cross3_nonnull']['rate'])}) | {f(r['null_rate']['voters'])} | **{r['outcome3']}** | {fl} |")
    L.append('\n| Slot | prediction (frozen) | Arm A | Arm B | reading (§7 table) | cross-arm equivalence Sonnet / GPT / Kimi | prediction |\n|---|---|---|---|---|---|---|')
    for s in SLOTS:
        a, b = P[s]['A']['outcome3'], P[s]['B']['outcome3']; xa = P[s]['cross_arm']
        if s == 'summary': verdict = 'control'
        else:
            acc, nullc, _ = PRED[s]; ok = b in acc
            if ok and nullc: ok = (P[s]['B']['null_rate']['voters'] or 0) < (P[s]['A']['null_rate']['voters'] or 0)
            verdict = '**held**' if ok else '**not held**'
        L.append(f"| `{s}` | {PRED[s][2]} | {a} | {b} | {reading(a, b)} | {' / '.join(f(xa[m]['rate']) for m in VOTERS)} | {verdict} |")
    L.append('\n### 1.1 Per corpus arm (outcome, three-voter rule)\n')
    L.append('| Slot | Arm | synthetic | conversational | pepys |\n|---|---|---|---|---|')
    for s in SLOTS:
        for arm in ARMS:
            L.append(f"| `{s}` | {arm} | " + ' | '.join(f"{T[c][s][arm]['outcome3']} ({f(T[c][s][arm]['cross3']['rate'])})" for c in CORPUS) + ' |')
    L.append('\n## 2. Two-voter sensitivity (Sonnet 5.5 + gpt-6.1-sol), beside the frozen verdict\n')
    L.append('The frozen three-voter rule decides. The two-voter column drops Kimi K2.6 (both remaining voters ≥ 0.80 and their pairwise cross ≥ 0.60 = pass); "Kimi alone" marks a slot × arm whose three-voter outcome is cut or borderline-cut only because Kimi missed repeatability while the two-voter rule passes.\n')
    L.append('| Slot | Arm | 3-voter | 2-voter | cross2 | Kimi rep | Kimi alone sank it |\n|---|---|---|---|---|---|---|')
    for s in SLOTS:
        for arm in ARMS:
            r = P[s][arm]; alone = r['outcome3'] in ('cut', 'borderline-cut') and r['voters_fail_repeat'] == ['kimi-k2.6'] and r['outcome2'] == 'pass'
            L.append(f"| `{s}` | {arm} | {r['outcome3']} | {r['outcome2']} | {f(r['cross2']['rate'])} | {f(r['stat_repeat']['kimi-k2.6'])} | {'**yes**' if alone else 'no'} |")
    L.append('\n## 3. Reported arms (no vote)\n')
    L.append('| Slot | Arm | Haiku rep | Haiku agrees with voting majority | mini rep | mini agrees with voting majority | cross over all five |\n|---|---|---|---|---|---|---|')
    for s in SLOTS:
        for arm in ARMS:
            r = P[s][arm]
            L.append(f"| `{s}` | {arm} | {f(r['stat_repeat']['claude-haiku-5-5'])} | {f(r['reported']['claude-haiku-5-5']['agree_with_majority'])} | {f(r['stat_repeat']['gpt-5.4-mini'])} | {f(r['reported']['gpt-5.4-mini']['agree_with_majority'])} | {f(r['cross_all5']['rate'])} |")
    L.append('\n## 4. Null rates per slot × arm × extractor (§8)\n')
    L.append('A slot whose null rate differs between arms by ≥ 0.20 (all five extractors) is flagged: the two definitions ask different questions.\n')
    L.append('| Slot | Arm | ' + ' | '.join(SHORT[m] for m in EXTRACTORS) + ' | all | arm diff | flag |\n|---|---|' + '---|' * len(EXTRACTORS) + '---|---|---|')
    for s in SLOTS:
        for arm in ARMS:
            r = P[s][arm]
            L.append(f"| `{s}` | {arm} | " + ' | '.join(f(r['null_rate'][m]) for m in EXTRACTORS) + f" | {f(r['null_rate']['all'])} | {f(P[s]['null_rate_arm_diff']) if arm == 'B' else ''} | {'**≥ 0.20**' if arm == 'B' and P[s]['null_diff_flag'] else ''} |")
    L.append('\n## 5. Per-extractor disagreement with the voting majority (wrong-rate proxy)\n')
    L.append('Run 2 has no wrongness judgment (the diagnostic of 2026-10-18 did; it was not repeated here). The proxy is the share of texts, among those where at least two of the three voters share a modal class, on which the extractor\'s modal class differs from that majority. For a voter the majority includes its own answer, so its figure is bounded by the other two agreeing against it.\n')
    L.append('| Slot | Arm | ' + ' | '.join(SHORT[m] for m in EXTRACTORS) + ' |\n|---|---|' + '---|' * len(EXTRACTORS))
    for s in SLOTS:
        for arm in ARMS:
            r = P[s][arm]; cells = []
            for m in EXTRACTORS:
                if m in REPORTED: v = r['reported'][m]['agree_with_majority']; cells.append(f(None if v is None else 1 - v))
                else: cells.append(f(None if r['cross3']['rate'] is None else r['_voter_disagree'][m]) if '_voter_disagree' in r else '—')
            L.append(f"| `{s}` | {arm} | " + ' | '.join(cells) + ' |')
    L.append('\n## 6. Task (a), conversational arm rebuilt on LoCoMo evidence sessions (R8; run-1 outputs, no calls)\n')
    L.append(f"Named items = the four sessions most cited as evidence by the LoCoMo QA set per conversation (fixed in the frozen plan §6 and re-derived here from `task_a_blocks.json`; a mismatch would have aborted). k = 3. Recency mean {f(ta['recency_mean'])}, random floor {f(ta['random_mean'])}. Pass: mean (salience − recency) ≥ 0.10 for ≥ 2 of the 3 voters.\n")
    L.append('| Policy | ' + ' | '.join(f"{SHORT[m]} hit / Δ" for m in ['claude-sonnet-5-5', 'claude-haiku-5-5', 'gpt-6.1-sol', 'kimi-k2.6']) + ' | voters ≥ +0.10 | pass |\n|---|---|---|---|---|---|---|')
    for pol, d in ta['per_policy'].items():
        L.append(f"| {pol} | " + ' | '.join(f"{f(d[m]['mean_salience_hit'])} / {f(d[m]['mean_diff_vs_recency'])}" for m in ['claude-sonnet-5-5', 'claude-haiku-5-5', 'gpt-6.1-sol', 'kimi-k2.6']) + f" | {d['voters_meeting_10pt']} | {'**yes**' if d['pass'] else 'no'} |")
    L.append('\n| Block | named | recency keeps | recency | random |\n|---|---|---|---|---|')
    for b in ta['blocks']: L.append(f"| {b['block']} | {', '.join(b['named'])} | {', '.join(b['recency_retained'])} | {f(b['recency'])} | {f(b['random'])} |")
    L.append('\nCaveat stated at freeze: two blocks of ten give a coarse statistic (steps of 0.125 in the mean); this is a finding about these two conversations.\n')
    L.append('## 7. Ruling drafts per slot (for the founder)\n')
    rp = os.path.join(EXP, 'ruling-drafts.md')
    L.append(open(rp, encoding='utf-8').read().strip() if os.path.exists(rp) else '_ruling-drafts.md not yet written_')
    L.append('')
    open(os.path.join(EXP, 'RESULTS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('RESULTS.md written; spend', round(tot, 2))


if __name__ == '__main__':
    main()
