"""RESULTS.md for the 2026-10-18 diagnostic: counts per slot per class (pooled and per arm), per-extractor wrong-rate,
ten worked examples per class, then the per-slot recommendations from recommendations.md (hand-written) verbatim.

Usage: python -P experiments/2026-10-18-diagnostic/scripts/results_md.py
"""
import json, os, sys
from collections import Counter, defaultdict
HERE = os.path.dirname(os.path.abspath(__file__)); DIAG = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from diagnostic import SLOTS, OLD, CK, ITEMS, EXTRACTORS, CAP_USD  # noqa: E402

ARMS = ('synthetic', 'conversational', 'pepys')
CLASSES = [('a', 'multiple valid referents'), ('b', 'extractor wrong'), ('c', 'granularity only'), ('d', 'null vs populated')]
SHORT = {'claude-sonnet-5-5': 'Sonnet 5.5', 'claude-haiku-5-5': 'Haiku 5.5', 'gpt-6.1-sol': 'gpt-6.1-sol', 'kimi-k2.6': 'Kimi K2.6'}
TEXTS_PER_ARM = 50


def esc(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def load():
    items = json.load(open(ITEMS, encoding='utf-8'))
    by_key = {(i['text_id'], i['slot']): i for i in items['items']}
    recs = {}; errors = Counter()
    if os.path.exists(CK):
        for l in open(CK, encoding='utf-8'):
            if not l.strip(): continue
            r = json.loads(l)
            if r.get('verdict'): recs[(r['text_id'], r['slot'])] = r
            else: errors[(r.get('error') or '')[:12]] += 1
    spend = json.load(open(os.path.join(DIAG, 'spend.json'), encoding='utf-8')) if os.path.exists(os.path.join(DIAG, 'spend.json')) else {'total_usd': 0, 'calls': 0, 'by_model': {}}
    return items, by_key, recs, errors, spend


def wrong_models(rec):
    inv = {lab: m for m, lab in rec['label_of'].items()}
    return [inv[l] for l in rec['verdict']['wrong'] if l in inv]


def pct(n, d):
    return '—' if not d else f'{n / d:.2f}'


def class_table(recs, by_key, scope_items, title):
    lines = [f'\n### {title}\n', '| Slot (v0.9 / v0.8.3) | items | (a) multiple valid | (b) extractor wrong | (c) granularity | (d) null vs populated | null present (a–c) | not judged |', '|---|---|---|---|---|---|---|---|']
    tot = Counter(); tot_items = 0; tot_np = 0; tot_nj = 0
    for s in SLOTS:
        keys = [k for k in scope_items if k[1] == s]
        c = Counter(); np_ = 0; nj = 0
        for k in keys:
            r = recs.get(k)
            if not r: nj += 1; continue
            v = r['verdict']; c[v['class']] += 1
            if v['class'] != 'd' and v['null_present']: np_ += 1
        n = len(keys) - nj
        cells = ' | '.join(f"{c[x]} ({pct(c[x], n)})" for x, _ in CLASSES)
        lines.append(f"| `{s}` / `{OLD[s]}` | {len(keys)} | {cells} | {np_} | {nj} |")
        tot.update(c); tot_items += len(keys); tot_np += np_; tot_nj += nj
    n = tot_items - tot_nj
    lines.append(f"| **all six** | {tot_items} | " + ' | '.join(f"{tot[x]} ({pct(tot[x], n)})" for x, _ in CLASSES) + f" | {tot_np} | {tot_nj} |")
    return lines


def main():
    items, by_key, recs, errors, spend = load()
    keys_all = sorted(by_key)
    judged = [k for k in keys_all if k in recs]
    L = []
    L.append('# RESULTS — diagnostic on run-1 disagreements, six core slots (2026-10-18)\n')
    L.append(f"Generated by `scripts/results_md.py` from `items.json` (built by `scripts/diagnostic.py` from `experiments/2026-10-17/raw/<model>/*.jsonl` and `raw/judge/*.jsonl`), `raw/diagnostic.jsonl` and `spend.json`. Judge calls only (`claude-opus-5-5`, `output_config.effort = \"low\"`, provider-default sampling); no extraction call; nothing pushed. Cap USD {CAP_USD:.0f}.\n")
    L.append('## 0. What was done\n')
    L.append('For each of the six core slots (v0.9 names; v0.8.3 `core.anchor`, `spark`, `wound`, `fuel`, `bridge`, `echo`) and each of the 150 run-1 texts, the four extractors\' **modal answers** were taken exactly as `score.py` takes them for the cross-model statistic: per extractor, the judge-equivalence class (from the run-1 Opus 5.5 judge pass, null included) that most of its five repeats fall in, represented by the most frequent wording in that class. Every text × slot whose four modal classes are not all the same is a **disagreement item**. One Opus 5.5 call per item classified the disagreement as (a) multiple valid referents in the text, (b) one or more extractors wrong (listing which), (c) granularity only (same referent, different specificity), or (d) null vs populated (with which side the text supports). Precedence fixed in the prompt: (b) over (a) and (c); (d) only when the populated answers are mutually equivalent, otherwise the populated disagreement is classified and `null_present` is set. Extractors were shown to the judge as anonymised labels A–D in a per-item shuffled order (`label_of` in each record); the labels are mapped back here. Prompts: `prompts/diagnostic_system.txt`, `prompts/diagnostic_user.txt`; the slot definitions shown to the judge are the run-1 extraction-prompt blocks verbatim (`items.json` → `definitions`).\n')
    L.append('**Ground truth.** The founder instruction asked for the authored value from the synthetic design matrix to be included where one exists. The design matrix (`experiments/2026-10-17/corpus/synthetic_design_matrix.json`) and the authored texts (`synthetic_texts_months_*.json` → `spans`) carry ground truth for `meaning`, `self_position`, `bodily_sensation`, `attribution`, `function`, `turning_point` and `trait` only; **no authored value exists for any of the six slots** (as `experiment-plan-run2.md` §8 already states), so none was passed and the synthetic arm is judged against the text alone, like the other two arms.\n')
    nerr = sum(errors.values())
    L.append('| Quantity | Value |\n|---|---|')
    L.append(f"| text × slot pairs | {6 * 150} |")
    L.append(f"| disagreement items (modal classes not all equal) | {len(keys_all)} |")
    L.append(f"| judged (valid verdict) | {len(judged)} |")
    L.append(f"| not judged (malformed after 3 attempts / cap) | {len(keys_all) - len(judged)} (checkpoint error records: {nerr}) |")
    jm = spend['by_model'].get('claude-opus-5-5', {})
    L.append(f"| judge calls / spend | {spend['calls']} / USD {spend['total_usd']:.2f} (in {jm.get('input_tokens', 0):,}, cached {jm.get('cached_input_tokens', 0):,}, cache write {jm.get('cache_write_tokens', 0):,}, out {jm.get('output_tokens', 0):,} tokens) |")
    L.append('')
    L.append('**Pilot gate (deviation, logged before the main run).** The first 12 calls (text in the user message, no cache on it, `max_tokens` 1500, rationale and evidence lengths unbounded beyond "one sentence" / 25 words) cost USD 0.0133 per call, projecting USD 8.6 for 645 items, above the cap. Two changes were made before call 13, neither changing what the judge reads: the source text became a cached prompt block and the slot calls of one text run in sequence so the block is reused; and the output schema bounded `evidence` to 15 words and `rationale` to 25 words (`max_tokens` 600). The 12 pilot verdicts are kept (same content, same classes).\n')
    L.append('Disagreement items per slot and arm (of 50 texts per arm):\n')
    L.append('| Slot | synthetic | conversational | pepys | pooled (of 150) |\n|---|---|---|---|---|')
    for s in SLOTS:
        c = Counter(by_key[k]['arm'] for k in keys_all if k[1] == s)
        L.append(f"| `{s}` | {c['synthetic']} | {c['conversational']} | {c['pepys']} | {sum(c.values())} |")
    L.append('')

    L.append('## 1. Counts per slot per class\n')
    L.append('Share in parentheses is of the judged items for that slot. "null present (a–c)" counts items classified (a), (b) or (c) in which at least one extractor was also null (not (d) because the populated answers themselves disagreed).')
    L.extend(class_table(recs, by_key, keys_all, 'Pooled (150 texts)'))
    for arm in ARMS:
        L.extend(class_table(recs, by_key, [k for k in keys_all if by_key[k]['arm'] == arm], f'{arm} arm (50 texts)'))
    # (d) direction
    L.append('\n### (d) which side the text supports\n')
    L.append('| Slot | (d) items | populated supported (null extractors wrong) | not supported (populated extractors wrong) |\n|---|---|---|---|')
    for s in SLOTS:
        ds = [recs[k]['verdict'] for k in judged if k[1] == s and recs[k]['verdict']['class'] == 'd']
        sup = sum(1 for v in ds if v['null_supported'] is True)
        L.append(f"| `{s}` | {len(ds)} | {sup} | {len(ds) - sup} |")
    # (a) referent counts
    L.append('\n### (a) how many valid referents the judge listed\n')
    L.append('| Slot | (a) items | 2 referents | 3 | 4+ | mean |\n|---|---|---|---|---|---|')
    for s in SLOTS:
        ns = [len(recs[k]['verdict']['referents']) for k in judged if k[1] == s and recs[k]['verdict']['class'] == 'a']
        if not ns: L.append(f"| `{s}` | 0 | — | — | — | — |"); continue
        L.append(f"| `{s}` | {len(ns)} | {sum(1 for n in ns if n <= 2)} | {sum(1 for n in ns if n == 3)} | {sum(1 for n in ns if n >= 4)} | {sum(ns) / len(ns):.1f} |")

    L.append('\n## 2. Per-extractor wrong-rate\n')
    L.append('Wrong-rate = items in which the judge named the extractor as wrong ÷ judged disagreement items for the slot (every extractor has a modal answer in every item). "(b)" counts class-(b) items only; "(b)+(d)" adds the null-vs-populated items, where the wrong side is the null extractors when the text supports the populated answer and the populated extractors when it does not. Denominators are disagreement items, not texts: a rate of 0.30 on `subject` (122 items) means the extractor was wrong on 37 of 150 texts.\n')
    for mode, title in (('b', '(b) only'), ('bd', '(b) + (d)')):
        L.append(f'\n### {title}\n')
        L.append('| Slot | items | ' + ' | '.join(SHORT[m] for m in EXTRACTORS) + ' |\n|---|---|' + '---|' * len(EXTRACTORS))
        tot = Counter(); tot_n = 0
        for s in SLOTS:
            ks = [k for k in judged if k[1] == s]
            c = Counter()
            for k in ks:
                v = recs[k]['verdict']
                if v['class'] == 'b' or (mode == 'bd' and v['class'] == 'd'):
                    for m in wrong_models(recs[k]): c[m] += 1
            L.append(f"| `{s}` | {len(ks)} | " + ' | '.join(f"{c[m]} ({pct(c[m], len(ks))})" for m in EXTRACTORS) + ' |')
            tot.update(c); tot_n += len(ks)
        L.append(f"| **all six** | {tot_n} | " + ' | '.join(f"{tot[m]} ({pct(tot[m], tot_n)})" for m in EXTRACTORS) + ' |')
    L.append('\n### (b) by arm, all six slots\n')
    L.append('| Arm | (b) items | ' + ' | '.join(SHORT[m] for m in EXTRACTORS) + ' |\n|---|---|' + '---|' * len(EXTRACTORS))
    for arm in ARMS:
        ks = [k for k in judged if by_key[k]['arm'] == arm and recs[k]['verdict']['class'] == 'b']
        c = Counter(m for k in ks for m in wrong_models(recs[k]))
        L.append(f"| {arm} | {len(ks)} | " + ' | '.join(f"{c[m]}" for m in EXTRACTORS) + ' |')
    L.append('\n### (c) which extractor gave the most specific answer\n')
    L.append('| Slot | (c) items | ' + ' | '.join(SHORT[m] for m in EXTRACTORS) + ' |\n|---|---|' + '---|' * len(EXTRACTORS))
    for s in SLOTS:
        ks = [k for k in judged if k[1] == s and recs[k]['verdict']['class'] == 'c']
        c = Counter()
        for k in ks:
            inv = {lab: m for m, lab in recs[k]['label_of'].items()}; ms = recs[k]['verdict'].get('most_specific')
            if ms in inv: c[inv[ms]] += 1
        L.append(f"| `{s}` | {len(ks)} | " + ' | '.join(str(c[m]) for m in EXTRACTORS) + ' |')

    L.append('\n## 3. Worked examples (ten per class)\n')
    L.append('Chosen round-robin over slots and arms in text-id order, so that every slot and arm appears where the class allows; nothing was selected by content. Modal answers are shown per extractor with the share of its five repeats in that modal class; "null" means the modal class was null. Evidence and rationale are the judge\'s, verbatim.\n')
    for cls, cname in CLASSES:
        L.append(f'\n### ({cls}) {cname}\n')
        pool = defaultdict(list)
        for k in judged:
            if recs[k]['verdict']['class'] == cls: pool[(k[1], by_key[k]['arm'])].append(k)
        order = [(s, a) for s in SLOTS for a in ARMS]
        chosen = []; idx = 0
        while len(chosen) < 10 and any(pool.values()):
            s, a = order[idx % len(order)]; idx += 1
            if pool[(s, a)]: chosen.append(pool[(s, a)].pop(0))
        if not chosen: L.append('_none_'); continue
        for n, k in enumerate(chosen, 1):
            it = by_key[k]; r = recs[k]; v = r['verdict']
            ans = '; '.join(f"**{SHORT[m]}**: {esc(json.dumps(p['answer'], ensure_ascii=False)) if p['class'] != 'null' else 'null'} ({p['n_in_class']}/{p['n_valid']})" for m, p in it['per_extractor'].items())
            extra = ''
            if cls == 'b': extra = f" Wrong: {', '.join(SHORT[m] for m in wrong_models(r)) or '—'}."
            if cls == 'a': extra = f" Referents: {esc('; '.join(v['referents']))}."
            if cls == 'c':
                inv = {lab: m for m, lab in r['label_of'].items()}; extra = f" Most specific: {SHORT.get(inv.get(v.get('most_specific')), '—')}."
            if cls == 'd': extra = f" Text supports the populated answer: {v['null_supported']}; wrong: {', '.join(SHORT[m] for m in wrong_models(r)) or '—'}."
            if v['null_present'] and cls != 'd': extra += ' (a null answer was also present)'
            L.append(f"{n}. **{k[0]}** ({it['arm']}), `{k[1]}`. {ans}.{extra} Evidence: “{esc(v.get('evidence') or 'none')}”. Rationale: {esc(v.get('rationale') or '')}")

    L.append('\n## 4. Recommendation per slot\n')
    rp = os.path.join(DIAG, 'recommendations.md')
    L.append(open(rp, encoding='utf-8').read().strip() if os.path.exists(rp) else '_recommendations.md not yet written_')
    L.append('')
    open(os.path.join(DIAG, 'RESULTS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print(f'RESULTS.md written: {len(judged)} judged of {len(keys_all)} items; spend USD {spend["total_usd"]:.2f}')


if __name__ == '__main__':
    main()
